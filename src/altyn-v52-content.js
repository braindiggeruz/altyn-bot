// ============================================================
// LEAD SCORING (cold / warm / hot)
// Simple deterministic rules. Output drives the owner card label.
// ============================================================
export function leadScore(user) {
  let score = 0;
  if (user?.scenario) score += 15;
  if (user?.quiz_completed_at) score += 10;
  if (user?.booking_intent_at) score += 25;
  if (user?.booking_confirmed_at) score += 40;
  if ((user?.direct_telegram_click_count || 0) >= 1) score += 30;
  if (user?.tornado_score) score += Math.min(user.tornado_score, 30);
  if (user?.source && user.source !== 'organic') score += 5;
  if (user?.creative) score += 5;
  const temperature = score >= 60 ? 'HOT' : score >= 30 ? 'WARM' : 'COLD';
  return { score, temperature };
}

